CREATE TABLE cc_admin_audit (
    audit_id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    actor_user_id NUMBER NOT NULL,
    target_user_id NUMBER NOT NULL,
    action_code VARCHAR2(12 CHAR) NOT NULL,
    previous_value VARCHAR2(20 CHAR) NOT NULL,
    new_value VARCHAR2(20 CHAR) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cc_admin_audit PRIMARY KEY (audit_id),
    CONSTRAINT fk_cc_admin_audit_actor FOREIGN KEY (actor_user_id) REFERENCES cc_users(user_id),
    CONSTRAINT fk_cc_admin_audit_target FOREIGN KEY (target_user_id) REFERENCES cc_users(user_id),
    CONSTRAINT ck_cc_admin_audit_action CHECK (action_code IN ('ROLE_CHANGE', 'ACTIVATE', 'DEACTIVATE'))
);

CREATE INDEX ix_cc_admin_audit_target ON cc_admin_audit(target_user_id, created_at);
CREATE INDEX ix_cc_admin_audit_actor ON cc_admin_audit(actor_user_id, created_at);
