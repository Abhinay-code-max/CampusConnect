-- Run manually while connected as CAMPUSCONNECT to FREEPDB1.
-- Oracle DDL commits implicitly. If this script stops part way through,
-- inspect USER_TABLES/USER_CONSTRAINTS and continue with missing objects;
-- do not drop objects or rerun blindly.

WHENEVER SQLERROR EXIT SQL.SQLCODE

CREATE TABLE cc_users (
    user_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                  (START WITH 1 INCREMENT BY 1),
    email         VARCHAR2(254 CHAR) NOT NULL,
    display_name  VARCHAR2(120 CHAR) NOT NULL,
    role_code     VARCHAR2(12 CHAR) NOT NULL,
    active_flag   CHAR(1 CHAR) DEFAULT 'Y' NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cc_users PRIMARY KEY (user_id),
    CONSTRAINT uq_cc_users_email UNIQUE (email),
    CONSTRAINT ck_cc_users_role CHECK (role_code IN ('STUDENT', 'ORGANIZER', 'JUDGE', 'ADMIN')),
    CONSTRAINT ck_cc_users_active CHECK (active_flag IN ('Y', 'N'))
);

CREATE TABLE cc_events (
    event_id             NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                         (START WITH 1 INCREMENT BY 1),
    event_code           VARCHAR2(40 CHAR) NOT NULL,
    event_name           VARCHAR2(160 CHAR) NOT NULL,
    description          VARCHAR2(2000 CHAR),
    owner_user_id        NUMBER NOT NULL,
    participation_mode   VARCHAR2(12 CHAR) NOT NULL,
    event_status         VARCHAR2(12 CHAR) DEFAULT 'DRAFT' NOT NULL,
    registration_opens   TIMESTAMP WITH TIME ZONE NOT NULL,
    registration_closes  TIMESTAMP WITH TIME ZONE NOT NULL,
    starts_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    ends_at              TIMESTAMP WITH TIME ZONE NOT NULL,
    capacity             NUMBER(8),
    location             VARCHAR2(200 CHAR),
    created_at           TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cc_events PRIMARY KEY (event_id),
    CONSTRAINT uq_cc_events_code UNIQUE (event_code),
    CONSTRAINT fk_cc_events_owner FOREIGN KEY (owner_user_id) REFERENCES cc_users (user_id),
    CONSTRAINT ck_cc_events_mode CHECK (participation_mode IN ('INDIVIDUAL', 'TEAM')),
    CONSTRAINT ck_cc_events_status CHECK (event_status IN ('DRAFT', 'PUBLISHED', 'CANCELLED', 'COMPLETED')),
    CONSTRAINT ck_cc_events_capacity CHECK (capacity IS NULL OR capacity > 0),
    CONSTRAINT ck_cc_events_dates CHECK (starts_at < ends_at),
    CONSTRAINT ck_cc_events_reg_dates CHECK (registration_opens <= registration_closes
                                               AND registration_closes <= starts_at)
);

CREATE TABLE cc_teams (
    team_id          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                     (START WITH 1 INCREMENT BY 1),
    team_name        VARCHAR2(120 CHAR) NOT NULL,
    created_by_user_id NUMBER NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cc_teams PRIMARY KEY (team_id),
    CONSTRAINT uq_cc_teams_owner_name UNIQUE (created_by_user_id, team_name),
    CONSTRAINT fk_cc_teams_creator FOREIGN KEY (created_by_user_id) REFERENCES cc_users (user_id)
);

CREATE TABLE cc_team_members (
    team_id    NUMBER NOT NULL,
    user_id    NUMBER NOT NULL,
    joined_at  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cc_team_members PRIMARY KEY (team_id, user_id),
    CONSTRAINT fk_cc_tm_team FOREIGN KEY (team_id) REFERENCES cc_teams (team_id),
    CONSTRAINT fk_cc_tm_user FOREIGN KEY (user_id) REFERENCES cc_users (user_id)
);

CREATE TABLE cc_registrations (
    registration_id     NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                        (START WITH 1 INCREMENT BY 1),
    event_id            NUMBER NOT NULL,
    registration_type   VARCHAR2(12 CHAR) NOT NULL,
    participant_user_id NUMBER,
    team_id             NUMBER,
    registration_status VARCHAR2(12 CHAR) DEFAULT 'CONFIRMED' NOT NULL,
    registered_at       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cc_registrations PRIMARY KEY (registration_id),
    CONSTRAINT uq_cc_reg_id_event UNIQUE (registration_id, event_id),
    CONSTRAINT fk_cc_reg_event FOREIGN KEY (event_id) REFERENCES cc_events (event_id),
    CONSTRAINT fk_cc_reg_user FOREIGN KEY (participant_user_id) REFERENCES cc_users (user_id),
    CONSTRAINT fk_cc_reg_team FOREIGN KEY (team_id) REFERENCES cc_teams (team_id),
    CONSTRAINT ck_cc_reg_subject CHECK (
        (registration_type = 'INDIVIDUAL' AND participant_user_id IS NOT NULL AND team_id IS NULL)
        OR
        (registration_type = 'TEAM' AND participant_user_id IS NULL AND team_id IS NOT NULL)
    ),
    CONSTRAINT ck_cc_reg_type CHECK (registration_type IN ('INDIVIDUAL', 'TEAM')),
    CONSTRAINT ck_cc_reg_status CHECK (
        registration_status IN ('CONFIRMED', 'WAITLISTED', 'CANCELLED')
    )
);

CREATE TABLE cc_event_judges (
    event_id       NUMBER NOT NULL,
    judge_user_id  NUMBER NOT NULL,
    assigned_at    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cc_event_judges PRIMARY KEY (event_id, judge_user_id),
    CONSTRAINT fk_cc_ej_event FOREIGN KEY (event_id) REFERENCES cc_events (event_id),
    CONSTRAINT fk_cc_ej_user FOREIGN KEY (judge_user_id) REFERENCES cc_users (user_id)
);

CREATE TABLE cc_scoring_criteria (
    criterion_id   NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                   (START WITH 1 INCREMENT BY 1),
    event_id       NUMBER NOT NULL,
    criterion_name VARCHAR2(120 CHAR) NOT NULL,
    max_points     NUMBER(8,2) NOT NULL,
    weight_percent NUMBER(5,2) DEFAULT 100 NOT NULL,
    display_order  NUMBER(4) DEFAULT 1 NOT NULL,
    CONSTRAINT pk_cc_scoring_criteria PRIMARY KEY (criterion_id),
    CONSTRAINT uq_cc_criteria_event_name UNIQUE (event_id, criterion_name),
    CONSTRAINT uq_cc_criteria_id_event UNIQUE (criterion_id, event_id),
    CONSTRAINT fk_cc_criteria_event FOREIGN KEY (event_id) REFERENCES cc_events (event_id),
    CONSTRAINT ck_cc_criteria_max CHECK (max_points > 0),
    CONSTRAINT ck_cc_criteria_weight CHECK (weight_percent > 0 AND weight_percent <= 100),
    CONSTRAINT ck_cc_criteria_order CHECK (display_order > 0)
);

CREATE TABLE cc_scores (
    score_id       NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY
                   (START WITH 1 INCREMENT BY 1),
    event_id       NUMBER NOT NULL,
    registration_id NUMBER NOT NULL,
    criterion_id   NUMBER NOT NULL,
    judge_user_id  NUMBER NOT NULL,
    awarded_points NUMBER(8,2) NOT NULL,
    feedback       VARCHAR2(1000 CHAR),
    submitted_at   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cc_scores PRIMARY KEY (score_id),
    CONSTRAINT uq_cc_score_once UNIQUE (registration_id, criterion_id, judge_user_id),
    CONSTRAINT fk_cc_score_reg_event FOREIGN KEY (registration_id, event_id)
        REFERENCES cc_registrations (registration_id, event_id),
    CONSTRAINT fk_cc_score_crit_event FOREIGN KEY (criterion_id, event_id)
        REFERENCES cc_scoring_criteria (criterion_id, event_id),
    CONSTRAINT fk_cc_score_judge FOREIGN KEY (event_id, judge_user_id)
        REFERENCES cc_event_judges (event_id, judge_user_id),
    CONSTRAINT ck_cc_score_points CHECK (awarded_points >= 0)
);

-- Index foreign-key and common filtering columns not already leading a unique index.
CREATE INDEX ix_cc_events_owner_start ON cc_events (owner_user_id, starts_at);
CREATE INDEX ix_cc_tm_user ON cc_team_members (user_id);
CREATE INDEX ix_cc_reg_event_status ON cc_registrations (event_id, registration_status);
CREATE INDEX ix_cc_reg_user ON cc_registrations (participant_user_id);
CREATE INDEX ix_cc_reg_team ON cc_registrations (team_id);
-- Filtered unique indexes avoid treating the inactive NULL subject as a
-- duplicate key: multiple teams or multiple individuals can register per event.
CREATE UNIQUE INDEX ux_cc_reg_event_user ON cc_registrations (
    CASE WHEN participant_user_id IS NOT NULL THEN event_id END,
    CASE WHEN participant_user_id IS NOT NULL THEN participant_user_id END
);
CREATE UNIQUE INDEX ux_cc_reg_event_team ON cc_registrations (
    CASE WHEN team_id IS NOT NULL THEN event_id END,
    CASE WHEN team_id IS NOT NULL THEN team_id END
);
CREATE INDEX ix_cc_ej_judge ON cc_event_judges (judge_user_id, event_id);
CREATE INDEX ix_cc_criteria_event_order ON cc_scoring_criteria (event_id, display_order);
CREATE INDEX ix_cc_scores_reg_event ON cc_scores (registration_id, event_id);
CREATE INDEX ix_cc_scores_crit_event ON cc_scores (criterion_id, event_id);
CREATE INDEX ix_cc_scores_event_judge ON cc_scores (event_id, judge_user_id);

PROMPT CampusConnect tables, constraints, and indexes created.
