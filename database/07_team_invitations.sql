-- Phase 6 additive migration. Run as CAMPUSCONNECT in FREEPDB1.
-- This creates invitation records only; existing teams and memberships are untouched.
CREATE TABLE cc_team_invitations (
    invitation_id      NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    team_id            NUMBER NOT NULL,
    invited_user_id    NUMBER NOT NULL,
    invited_by_user_id NUMBER NOT NULL,
    invitation_status VARCHAR2(12 CHAR) DEFAULT 'PENDING' NOT NULL,
    created_at         TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    responded_at       TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_cc_team_invitations PRIMARY KEY (invitation_id),
    CONSTRAINT fk_cc_ti_team FOREIGN KEY (team_id) REFERENCES cc_teams(team_id),
    CONSTRAINT fk_cc_ti_invited FOREIGN KEY (invited_user_id) REFERENCES cc_users(user_id),
    CONSTRAINT fk_cc_ti_inviter FOREIGN KEY (invited_by_user_id) REFERENCES cc_users(user_id),
    CONSTRAINT ck_cc_ti_status CHECK (invitation_status IN ('PENDING','ACCEPTED','DECLINED','CANCELLED')),
    CONSTRAINT ck_cc_ti_response CHECK (
        (invitation_status = 'PENDING' AND responded_at IS NULL)
        OR (invitation_status <> 'PENDING' AND responded_at IS NOT NULL)
    )
);

-- Only one outstanding invitation for a team and student; history is retained.
CREATE UNIQUE INDEX ux_cc_ti_pending ON cc_team_invitations (
    CASE WHEN invitation_status = 'PENDING' THEN team_id END,
    CASE WHEN invitation_status = 'PENDING' THEN invited_user_id END
);
CREATE INDEX ix_cc_ti_recipient ON cc_team_invitations (invited_user_id, invitation_status, created_at);
